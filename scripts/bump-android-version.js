#!/usr/bin/env node

/**
 * Android Version Auto-Bump Script
 * Automatically increments versionCode and optionally versionName
 * 
 * Usage:
 *   node scripts/bump-android-version.js [patch|minor|major]
 *   Default: patch (increments versionCode only)
 */

const fs = require('fs');
const path = require('path');

const VERSION_PROPS_PATH = path.join(__dirname, '..', 'android', 'version.properties');
const PACKAGE_JSON_PATH = path.join(__dirname, '..', 'package.json');
const APP_VERSION_TS_PATH = path.join(__dirname, '..', 'src', 'config', 'appVersion.generated.ts');

// Parse version string (e.g., "1.0.0") into parts
function parseVersion(version) {
  const parts = version.split('.').map(Number);
  return {
    major: parts[0] || 0,
    minor: parts[1] || 0,
    patch: parts[2] || 0,
    toString() {
      return `${this.major}.${this.minor}.${this.patch}`;
    }
  };
}

// Increment version based on type
function incrementVersion(version, type = 'patch') {
  const v = parseVersion(version);
  
  switch (type) {
    case 'major':
      v.major++;
      v.minor = 0;
      v.patch = 0;
      break;
    case 'minor':
      v.minor++;
      v.patch = 0;
      break;
    case 'patch':
    default:
      v.patch++;
      break;
  }
  
  return v.toString();
}

// Load and save android/version.properties
function loadVersionProps() {
  const defaults = { VERSION_CODE: '3', VERSION_NAME: '1.0.0' };

  if (!fs.existsSync(VERSION_PROPS_PATH)) {
    return { ...defaults };
  }

  const content = fs.readFileSync(VERSION_PROPS_PATH, 'utf8');
  const lines = content.split('\n');
  const props = { ...defaults };

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const [key, value] = trimmed.split('=');
    if (key && value !== undefined) {
      props[key.trim()] = value.trim();
    }
  }

  return props;
}

function saveVersionProps(props) {
  const lines = [
    `VERSION_CODE=${props.VERSION_CODE}`,
    `VERSION_NAME=${props.VERSION_NAME}`,
    ''
  ];

  fs.writeFileSync(VERSION_PROPS_PATH, lines.join('\n'), 'utf8');
}

// Generate TypeScript config file for app version (used by JS/TS layer)
function writeAppVersionConfig(props) {
  const versionName = props.VERSION_NAME;
  const versionCode = parseInt(props.VERSION_CODE, 10) || 0;

  const fileContents = `// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// This file is generated by scripts/bump-android-version.js
// It keeps the JS/TS layer in sync with native Android versioning.

export const APP_VERSION_NAME = '${versionName}';
export const APP_VERSION_CODE = ${versionCode};
`;

  fs.writeFileSync(APP_VERSION_TS_PATH, fileContents, 'utf8');
}

// Read and update android/version.properties - only bump versionCode
function bumpAndroidVersionCode() {
  const props = loadVersionProps();

  const currentVersionCode = parseInt(props.VERSION_CODE, 10) || 0;
  const newVersionCode = currentVersionCode + 1;

  props.VERSION_CODE = String(newVersionCode);
  saveVersionProps(props);

  // Keep JS/TS layer in sync
  writeAppVersionConfig(props);

  console.log('✅ Android versionCode bumped successfully!');
  console.log(`   versionCode: ${currentVersionCode} → ${newVersionCode}`);

  return { versionCode: newVersionCode, versionName: props.VERSION_NAME };
}

// Read and update android/version.properties - bump both versionCode and versionName
function bumpAndroidVersion(bumpType = 'patch') {
  const props = loadVersionProps();

  const currentVersionCode = parseInt(props.VERSION_CODE, 10) || 0;
  const newVersionCode = currentVersionCode + 1;

  const currentVersionName = props.VERSION_NAME;
  const newVersionName = incrementVersion(currentVersionName, bumpType);

  props.VERSION_CODE = String(newVersionCode);
  props.VERSION_NAME = newVersionName;
  saveVersionProps(props);

  // Keep JS/TS layer in sync
  writeAppVersionConfig(props);

  console.log('✅ Android version bumped successfully!');
  console.log(`   versionCode: ${currentVersionCode} → ${newVersionCode}`);
  console.log(`   versionName: ${currentVersionName} → ${newVersionName}`);

  return { versionCode: newVersionCode, versionName: newVersionName };
}

// Update package.json version
function updatePackageJsonVersion(newVersion) {
  if (!fs.existsSync(PACKAGE_JSON_PATH)) {
    console.warn('⚠️  package.json not found, skipping version update');
    return;
  }
  
  const packageJson = JSON.parse(fs.readFileSync(PACKAGE_JSON_PATH, 'utf8'));
  const oldVersion = packageJson.version;
  packageJson.version = newVersion;
  
  fs.writeFileSync(PACKAGE_JSON_PATH, JSON.stringify(packageJson, null, 2) + '\n', 'utf8');
  console.log(`   package.json: ${oldVersion} → ${newVersion}`);
}

// Main execution
const bumpType = process.argv[2] || 'patch';
const codeOnly = process.argv[2] === 'code-only' || process.argv.includes('--code-only');

if (codeOnly) {
  // Only bump versionCode (for Play Store builds)
  try {
    bumpAndroidVersionCode();
    console.log('\n🎉 VersionCode bump complete!');
  } catch (error) {
    console.error('❌ Error bumping versionCode:', error.message);
    process.exit(1);
  }
} else {
  // Bump both versionCode and versionName
  if (!['patch', 'minor', 'major'].includes(bumpType)) {
    console.error('❌ Invalid bump type. Use: patch, minor, major, or code-only');
    process.exit(1);
  }

  try {
    const { versionName } = bumpAndroidVersion(bumpType);
    updatePackageJsonVersion(versionName);
    console.log('\n🎉 Version bump complete!');
  } catch (error) {
    console.error('❌ Error bumping version:', error.message);
    process.exit(1);
  }
}
